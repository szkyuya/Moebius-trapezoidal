Randomized Möbius-Transformed Trapezoidal Rule with a random number of points.

This is the rule of Definition 4.1 in arXiv:2407.13650. Besides the random
shift delta of cot_trap_randomized.m, the number of points m is drawn uniformly
from {floor(n/2),...,n}, and the m point rule with theta_j = 2*pi*(j+delta)/m,
j = 0,...,m-1, is applied. Every sample is an unbiased estimate of the integral,
and the worst-case root-mean-squared error over the weighted Sobolev space of
smoothness alpha is of the optimal order n^(-alpha-1/2) (Theorem 4.2 therein),
half an order better than with a fixed number of points.

The gain concerns the worst case, i.e. integrands with strong oscillations at a
frequency close to n after the transformation, which a fixed n aliases
completely. For integrands whose transformed Fourier coefficients decay
regularly, such as |x|, both rules converge at the same rate, and this rule has
a somewhat larger error since it uses about 3n/4 points per sample on average.
Part 2 below compares the two rules on such a worst-case integrand.

Y. Suzuki, N. Hyvönen, and T. Karvonen. “Möbius-Transformed Trapezoidal Rule”.
AMS Mathematics of Computation 95 (2026), no. 359, 1491–1515. DOI:10.1090/mcom/4084

