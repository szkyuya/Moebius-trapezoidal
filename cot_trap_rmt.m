%% Mobius transform
phi= @(z) -cot(z./2); % mobius transform
phi_=@(z) 1./(2.*(sin(z./2)).^2); % Jacobian
% angles of the rule with m points and the shift delta; rand returns values in
% the open interval (0,1), so theta=0 (that is, x=-Inf) is never used
nodes= @(m,delta) 2*pi*((0:m-1)+delta)/m;
% one sample of the rule, for a vectorized integrand h and weight rho
sample= @(h,rho,m,delta) 2*pi/m*sum(h(phi(nodes(m,delta))).*rho(phi(nodes(m,delta))).*phi_(nodes(m,delta)));
M=12; %number of points; calculated up until 2^M points
R=16; %number of independent samples for each n
rng(2025); %seed of the random number generator, for reproducibility
%% Define your weight
rho= @(x) exp(-(x.^2)./2)./sqrt(2*pi);
%% Define your integrand function (it must accept vectors)
p=1;%parameter in the integrand, |x|^p
f= @(x) abs(x).^p;

trueI=sqrt((2^p)/pi)*gamma((p+1)/2); %true integral value, only for the absolute error

%% Part 1: estimate with a standard error
res=zeros(4,M); %rows: n, estimate, standard error, absolute error
for ni=2:M
n=2^ni; % maximal number of points
est=zeros(R,1);
for r=1:R
m=randi([floor(n/2),n]); % random number of points
delta=rand; % random shift in [0,1)
est(r)=sample(f,rho,m,delta);
end
res(:,ni)=[n; mean(est); std(est)/sqrt(R); abs(trueI-mean(est))];
fprintf('n = %5d   estimate = %.10f   standard error = %.3e   absolute error = %.3e\n', res(:,ni));
end

figure;
loglog(res(1,2:end),res(3,2:end),'o-',res(1,2:end),res(4,2:end),'s-')
legend('Standard error','Absolute error')
title('Rule with a random number of points')
xlabel('n')
ylabel('Error')

%% Part 2: root-mean-squared error in the worst case
% The integrand cos(n*theta(x)), with theta(x) the inverse of x=-cot(theta/2),
% has the frequency n after the transformation. The n point rule with a random
% shift aliases it completely, the rule with a random number of points does not.
theta_inv= @(x) 2*atan2(1,-x); % inverse of the Mobius transform
Rrmse=200; % repetitions for the root-mean-squared error
ns=2.^(5:9);
rmse=zeros(2,numel(ns)); %rows: random shift only, random number of points
for i=1:numel(ns)
n=ns(i);
h= @(x) cos(n*theta_inv(x));
exactI=sample(h,rho,3^10,0.5); % reference value with many points
e_shift=zeros(Rrmse,1); e_rmt=zeros(Rrmse,1);
for r=1:Rrmse
e_shift(r)=sample(h,rho,n,rand);
e_rmt(r)=sample(h,rho,randi([floor(n/2),n]),rand);
end
rmse(:,i)=[sqrt(mean((e_shift-exactI).^2)); sqrt(mean((e_rmt-exactI).^2))];
fprintf('n = %4d   RMSE random shift = %.2e   RMSE random number of points = %.2e\n', n, rmse(:,i));
end

figure;
loglog(ns,rmse(1,:),'o-',ns,rmse(2,:),'s-')
legend('Random shift, n points','Random shift and random number of points')
title('RMSE for the integrand cos(n\theta(x))')
xlabel('n')
ylabel('RMSE')
