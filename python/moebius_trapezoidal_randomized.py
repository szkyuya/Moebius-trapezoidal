def integrate_randomized(f: Callable, n: int, weight: Weight = "gaussian", *,
                         n_shifts: int = 16, rng=None, scale: float = 1.0,
                         loc: float = 0.0, vectorized: bool = True) -> RandomizedResult:
    """Randomly shifted Möbius-transformed trapezoidal rule with a standard error.

    The n point rule is applied with ``n_shifts`` independent uniform random
    shifts, so f is evaluated at ``n * n_shifts`` points in total.

    Parameters
    ----------
    f : callable
        Integrand, as in :func:`moebius_trapezoidal.integrate`. Vector or
        matrix valued integrands are supported.
    n : int
        Number of points of each shifted rule.
    weight, scale, loc, vectorized
        As in :func:`moebius_trapezoidal.integrate`.
    n_shifts : int
        Number of independent random shifts, at least 2.
    rng : numpy.random.Generator, int or None
        Random number generator, or a seed for ``numpy.random.default_rng``.

    Returns
    -------
    RandomizedResult
        Named tuple ``(value, std_error, estimates, n, n_shifts)``. ``value`` is
        the mean of the ``n_shifts`` estimates and ``std_error`` is their sample
        standard deviation divided by ``sqrt(n_shifts)``. For instance,
        ``value ± 2 * std_error`` is an approximate 95% confidence interval.
    """
    if not (isinstance(n_shifts, (int, np.integer)) and n_shifts >= 2):
        raise ValueError("n_shifts must be an integer of at least 2 to estimate the error")
    rng = np.random.default_rng(rng)
    estimates = []
    for shift in rng.random(n_shifts):
        x, w = shifted_nodes_weights(n, float(shift), weight, scale=scale, loc=loc)
        y = _evaluate(f, x, vectorized)
        estimates.append(np.tensordot(w, y, axes=(0, 0)))
    estimates = np.asarray(estimates)
    value = estimates.mean(axis=0)
    std_error = estimates.std(axis=0, ddof=1) / np.sqrt(n_shifts)
    return RandomizedResult(value, std_error, estimates, n, n_shifts)


