def shifted_nodes_weights(n: int, shift: float, weight: Weight = "gaussian", *,
                          scale: float = 1.0, loc: float = 0.0, prune: bool = True):
    """Nodes and weights of the n point rule with the angles θ_k = 2π(k + shift)/n.

    Parameters
    ----------
    n : int
        Number of points.
    shift : float
        Shift in units of the grid step, ``0 <= shift < 1``. ``shift=0.5`` gives
        the deterministic rule of :func:`moebius_trapezoidal.nodes_weights`.
    weight, scale, loc, prune
        As in :func:`moebius_trapezoidal.nodes_weights`.

    Returns
    -------
    x, w : ndarray
        Nodes in increasing order and the corresponding weights.
    """
    _check(n, scale)
    if not 0.0 <= shift < 1.0:
        raise ValueError("shift must satisfy 0 <= shift < 1")
    rho = _resolve_weight(weight)
    theta = 2.0 * np.pi * (np.arange(n) + shift) / n
    w = np.zeros(n)
    x = np.full(n, -np.inf)
    inner = theta > 0  # θ = 0 is x = ±∞, where the weighted integrand vanishes
    x[inner] = moebius_transform(theta[inner], scale, loc)
    w[inner] = (2.0 * np.pi / n) * moebius_jacobian(theta[inner], scale)
    if rho is not None:
        w[inner] = w[inner] * np.asarray(rho(x[inner]), dtype=float)
    if prune:
        keep = w != 0
        x, w = x[keep], w[keep]
    return x, w


