Randomly shifted Möbius-Transformed Trapezoidal Rule with an error estimate.

The fixed shift of cot_trap.m is replaced by a uniform random shift delta,
theta_j = 2*pi*(j+delta)/n for j = 0,...,n-1. For every delta the rule is a
valid quadrature rule, and its expectation over delta is exactly the integral.
Repeating it with R independent shifts gives R unbiased estimates, whose mean
is the final estimate and whose standard deviation divided by sqrt(R) is its
standard error.

Y. Suzuki, N. Hyvönen, and T. Karvonen. “Möbius-Transformed Trapezoidal Rule”.
AMS Mathematics of Computation 95 (2026), no. 359, 1491–1515. DOI:10.1090/mcom/4084

