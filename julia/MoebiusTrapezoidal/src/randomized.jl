# Randomly shifted Möbius-transformed trapezoidal rule with an error estimate.
#
# Instead of the fixed half step shift, the equispaced angles are shifted by a
# random amount, θₖ = 2π(k + u)/n, k = 0, …, n-1, u ~ Uniform[0, 1). For every
# u the rule is a valid quadrature rule, and since u is uniform over one grid
# step, its expectation is exactly the integral. Repeating this with R
# independent shifts gives R unbiased estimates, whose mean is the final
# estimate and whose standard deviation divided by sqrt(R) is its standard
# error. With u = 1/2 the rule is the deterministic rule of moebius_nodes.
#
# See also T. Goda, Y. Kazashi, and Y. Suzuki, "Randomizing the trapezoidal rule
# gives the optimal RMSE rate in Gaussian Sobolev spaces", AMS Mathematics of
# Computation 93 (2024), 1655–1676, DOI: 10.1090/mcom/3910.
#
# This file is included by MoebiusTrapezoidal.jl. It was generated by Claude,
# Anthropic's AI assistant, based on the Matlab version cot_trap.m written by
# Yuya Suzuki.

"""
    moebius_nodes_shifted(n, shift, weight=gaussian_weight; scale=1, loc=0, T=Float64, prune=true) -> (x, w)

Nodes and weights of the `n` point rule with the angles `θₖ = 2π(k + shift)/n`,
`k = 0, …, n-1`, where `0 ≤ shift < 1` is given in units of the grid step.
`shift = 1/2` gives [`moebius_nodes`](@ref). The other arguments are as in
[`moebius_nodes`](@ref).
"""
function moebius_nodes_shifted(n::Integer, shift::Real, weight=gaussian_weight;
                               scale::Real=1, loc::Real=0,
                               T::Type{<:AbstractFloat}=Float64, prune::Bool=true)
    _check(n, scale)
    0 ≤ shift < 1 || throw(ArgumentError("shift must satisfy 0 ≤ shift < 1, got $shift"))
    ρ = _resolve(weight)
    s, l, u = T(scale), T(loc), T(shift)
    h = 2 * T(π) / n
    x = Vector{T}(undef, n)
    w = Vector{T}(undef, n)
    for k in 0:n-1
        θ = h * (k + u)
        if iszero(θ)
            # θ = 0 is x = ±∞, where the weighted integrand vanishes
            x[k+1] = -T(Inf)
            w[k+1] = zero(T)
        else
            x[k+1] = moebius_transform(θ; scale=s, loc=l)
            w[k+1] = h * moebius_jacobian(θ; scale=s) * _weight(ρ, x[k+1])
        end
    end
    if prune
        keep = w .!= 0
        return x[keep], w[keep]
    end
    return x, w
end

"""
    moebius_trap_randomized(f, n, weight=gaussian_weight; nshifts=16, rng=default_rng(),
                            scale=1, loc=0, T=Float64) -> (; value, std_error, estimates, n, nshifts)

Randomly shifted Möbius-transformed trapezoidal rule with a standard error.

The `n` point rule is applied with `nshifts` independent uniform random shifts,
so `f` is evaluated at `n * nshifts` points in total. `value` is the mean of the
`estimates` and `std_error` is their sample standard deviation divided by
`sqrt(nshifts)`; for instance, `value ± 2std_error` is an approximate 95%
confidence interval. `f` may return a number or an array.

# Examples
```julia
using Random
r = moebius_trap_randomized(abs, 257; rng=MersenneTwister(1))
r.value, r.std_error
```
"""
function moebius_trap_randomized(f, n::Integer, weight=gaussian_weight; nshifts::Integer=16,
                                 rng::AbstractRNG=default_rng(),
                                 T::Type{<:AbstractFloat}=Float64, kwargs...)
    nshifts ≥ 2 || throw(ArgumentError("nshifts must be at least 2 to estimate the error, got $nshifts"))
    estimates = map(1:nshifts) do _
        x, w = moebius_nodes_shifted(n, rand(rng, T), weight; T=T, kwargs...)
        isempty(x) && throw(ArgumentError("all weights underflow to zero, increase n or check the weight"))
        sum(w[i] * f(x[i]) for i in eachindex(x, w))
    end
    value = sum(estimates) / nshifts
    variance = sum(e -> abs2.(e .- value), estimates) / (nshifts - 1)  # numbers and arrays
    std_error = sqrt.(variance ./ nshifts)
    return (; value, std_error, estimates, n, nshifts)
end
